"""Row selection for `--ids` (§7.3.3).

`--ids` names the rows to execute; every other input row is inherited from the
input file. Parsing the flag and resolving it against the rows are kept apart
because they fail for different reasons and at different times: a malformed
token is bad CLI syntax, while an id that is not in the file can only be
discovered once the CSV has been read.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

from .csv_io import EvalRow


#: Separator for an inclusive span of rows, e.g. `q-0021..q-0024`.
SPAN = ".."


class IdSelectionError(ValueError):
    """A `--ids` selection that is malformed, unknown, or resolves to nothing (§7.10)."""


@dataclass(frozen=True)
class IdSelection:
    """A parsed `--ids` value. Single ids are stored as one-row spans."""

    raw: str
    spans: tuple[tuple[str, str], ...]

    def ids(self) -> list[str]:
        """Every id named in the flag, spans counted by their two ends only."""
        seen: list[str] = []
        for start, end in self.spans:
            for qid in (start, end):
                if qid not in seen:
                    seen.append(qid)
        return seen

    def resolve(self, rows: Sequence[EvalRow]) -> list[str]:
        """Return the `question_id`s to execute, in input-file order.

        File order is the authority, exactly as it is for `--from` (§7.3.2):
        ids are strings, a merged eval set may not sort in execution order, and
        the CSV's row order is the order `evalrun` runs and preserves. So the
        order the flag happened to name rows in cannot affect the result, and a
        repeated id collapses.
        """
        if not self.spans:
            raise IdSelectionError(
                "--ids resolved to zero rows: nothing to run. "
                "Pass at least one question_id, or drop the flag to run the whole file."
            )

        position: dict[str, int] = {}
        for i, row in enumerate(rows):
            position.setdefault(row.question_id, i)

        unknown = [qid for qid in self.ids() if qid not in position]
        if unknown:
            # Every unknown id at once, not just the first: the usual cause is a
            # stale list pasted from an older eval set, and a run that executed
            # only the ids it recognised would report a fixed row as untouched.
            raise IdSelectionError(
                f"unknown question_ids in --ids: {', '.join(unknown)}. "
                f"The input file has {len(rows)} row(s), none with those ids."
            )

        selected: set[str] = set()
        for start, end in self.spans:
            a, b = position[start], position[end]
            if b < a:
                raise IdSelectionError(
                    f"span {start}{SPAN}{end} ends before it starts in the input file "
                    f"(row {b + 1} comes before row {a + 1}). Spans are resolved by file "
                    "position, so name the earlier row first."
                )
            selected.update(row.question_id for row in rows[a : b + 1])

        return [row.question_id for row in rows if row.question_id in selected]


def parse_ids(value: str) -> IdSelection:
    """Parse `--ids q-0007,q-0021..q-0024,q-0090` into an `IdSelection`.

    Empty entries are skipped rather than rejected so a list generated by a
    shell one-liner can end in a comma (§7.3.3). A list that is empty after
    that is not an error here — it fails at resolve time, with the message the
    operator needs, alongside every other way the selection can come to nothing.
    """
    spans: list[tuple[str, str]] = []
    for token in value.split(","):
        token = token.strip()
        if not token:
            continue
        if SPAN not in token:
            spans.append((token, token))
            continue
        ends = token.split(SPAN)
        if len(ends) != 2:
            raise IdSelectionError(
                f"{token!r} is not a span: expected `start{SPAN}end` with one separator."
            )
        start, end = (e.strip() for e in ends)
        if not start or not end:
            raise IdSelectionError(
                f"{token!r} is a half-open span. Both ends are required — "
                "name the first and last row of the range."
            )
        spans.append((start, end))
    return IdSelection(raw=value, spans=tuple(spans))


__all__ = ["SPAN", "IdSelection", "IdSelectionError", "parse_ids"]
